import {chromium, expect} from '@playwright/test';
import assert from 'node:assert/strict';
import {mkdir, readFile} from 'node:fs/promises';
import {pathToFileURL} from 'node:url';
import {resolve} from 'node:path';

// Standalone ecosystem page only. Does not change driving-game state or assets.
const url=process.env.TEST_CARE_CITY_URL||'http://127.0.0.1:5191/care-city/index.html';
const browser=await chromium.launch({channel:'chrome',headless:true,args:['--use-angle=swiftshader','--enable-unsafe-swiftshader']});
await mkdir('.test-artifacts',{recursive:true});
const result={};
try {
  const page=await browser.newPage({viewport:{width:1500,height:1000}}), errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  // Optional typography must never be needed by the 3D engines or directory.
  await page.route(/^https?:\/\/(?!127\.0\.0\.1)/,route=>route.abort());
  await page.goto(url);
  await expect.poll(()=>page.evaluate(()=>window.LohasCareCity?.getState().ready)).toBe(true);
  await expect(page.locator('[data-unit]')).toHaveCount(36);
  const data=await page.locator('#units-data').textContent().then(JSON.parse);
  assert.equal(new Set(data.map(u=>u.id)).size,36);
  assert.deepEqual(Object.fromEntries(['core','day','residential','home','logistics'].map(c=>[c,data.filter(u=>u.category===c).length])),{core:6,day:5,residential:12,home:11,logistics:2});
  assert.equal(data.filter(u=>u.name==='樂活島').length,1);
  assert.equal(data.find(u=>u.name==='樂活島').category,'core');
  assert.equal(data.filter(u=>u.floors).length,1);
  assert.equal(data.find(u=>u.id==='hq').floors.length,2);
  assert.ok(data.some(u=>u.name==='北門綜合長照機構'));
  assert.ok(data.every(u=>u.address===null&&u.phone===null));
  for(const [category,count] of Object.entries({core:6,day:5,residential:12,home:11,logistics:2})){
    await page.locator('[data-category='+category+']').click();
    await expect(page.locator('[data-unit]')).toHaveCount(count);
  }
  await page.locator('#overview').click();
  await page.locator('#search').fill('北門');
  await expect(page.locator('[data-unit]')).toHaveCount(1);
  await page.locator('[data-unit=res-11]').click();
  await expect(page.locator('#detail-title')).toHaveText('北門綜合長照機構');
  await page.keyboard.press('Escape');
  await expect(page.locator('[data-unit=res-11]')).toBeFocused();
  await page.locator('#search').fill('查無此單位');
  await expect(page.locator('#clear-search')).toBeVisible();
  await page.locator('#clear-search').click();
  await expect(page.locator('[data-unit]')).toHaveCount(36);
  await page.locator('#hq-focus').click();
  await expect(page.locator('#floor-panel')).toContainText('出餐');
  await page.locator('#floor-tab-0').focus();
  await page.keyboard.press('ArrowRight');
  await expect(page.locator('#floor-tab-1')).toHaveAttribute('aria-selected','true');
  await expect(page.locator('#floor-panel')).toContainText('營運決策');
  await expect.poll(()=>page.evaluate(()=>window.LohasCareCity.getState().camera[3])).toBeGreaterThan(3);
  await page.screenshot({path:'.test-artifacts/care-city-hq.png'});
  await page.keyboard.press('Escape');
  await page.locator('#overview').click();
  await expect.poll(()=>page.evaluate(()=>window.LohasCareCity.getState().camera[3])).toBe(1);
  const projected=await page.evaluate(()=>window.LohasCareCity.projectUnit('hq'));
  await page.mouse.move(projected.x,projected.y);
  await expect(page.locator('#tooltip')).toContainText('樂活長照集團總部');
  await page.mouse.click(projected.x,projected.y);
  await expect(page.locator('#detail-title')).toHaveText('樂活長照集團總部');
  await page.keyboard.press('Escape');
  await page.locator('#overview').click();
  await expect.poll(()=>page.evaluate(()=>window.LohasCareCity.getState().camera[3])).toBe(1);
  const canvas=page.locator('#scene canvas'), bounds=await canvas.boundingBox();
  await page.mouse.move(bounds.x+bounds.width*.5,bounds.y+bounds.height*.55);
  await page.mouse.down();await page.mouse.move(bounds.x+bounds.width*.5+45,bounds.y+bounds.height*.55+15,{steps:8});await page.mouse.up();
  await expect(page.locator('#drawer')).toBeHidden();
  const movingBefore=await page.evaluate(()=>window.LohasCareCity.getState().vehicles);
  await page.waitForTimeout(500);
  assert.notDeepEqual(await page.evaluate(()=>window.LohasCareCity.getState().vehicles),movingBefore);
  await page.locator('#motion').click();
  const stopped=await page.evaluate(()=>window.LohasCareCity.getState().vehicles);
  await page.waitForTimeout(300);
  assert.deepEqual(await page.evaluate(()=>window.LohasCareCity.getState().vehicles),stopped);
  await page.locator('#overview').click();await page.waitForTimeout(1300);
  await page.screenshot({path:'.test-artifacts/care-city-desktop.png'});
  await page.setViewportSize({width:390,height:844});
  await page.waitForTimeout(300);
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth),390);
  await page.screenshot({path:'.test-artifacts/care-city-mobile.png'});
  await page.locator('#open-list').click();
  await page.locator('#search').fill('永夏');
  await page.locator('[data-unit=home-2]').click();
  await expect(page.locator('#drawer')).toContainText('第一健康生技有限公司');
  await page.locator('#close-detail').click();
  await page.locator('#hq-mobile').click();
  await expect(page.locator('#floor-tab-0')).toBeVisible();
  await page.locator('#close-detail').click();
  await page.locator('#help').click();await expect(page.locator('#help-dialog')).toBeVisible();
  await page.keyboard.press('Escape');await expect(page.locator('#help-dialog')).not.toBeVisible();
  assert.deepEqual(errors,[]);
  result.desktopMobileInteractions='passed';
  const offline=await browser.newContext({offline:true,reducedMotion:'reduce'});
  const filePage=await offline.newPage();
  await filePage.goto(pathToFileURL(resolve('public/care-city/index.html')).href);
  await expect.poll(()=>filePage.evaluate(()=>window.LohasCareCity?.getState().ready)).toBe(true);
  assert.equal(await filePage.evaluate(()=>window.LohasCareCity.getState().paused),true);
  await filePage.locator('#hq-focus').click();await expect(filePage.locator('#floor-panel')).toBeVisible();
  await offline.close();result.offlineFileAndReducedMotion='passed';
  const fallback=await browser.newPage();
  await fallback.route(/^https?:\/\/(?!127\.0\.0\.1)/,route=>route.abort());
  await fallback.addInitScript(()=>{const original=HTMLCanvasElement.prototype.getContext;HTMLCanvasElement.prototype.getContext=function(type,...args){return String(type).startsWith('webgl')?null:original.call(this,type,...args);};});
  await fallback.goto(url);
  await expect(fallback.locator('#loading')).toContainText('此裝置無法開啟');
  await fallback.locator('[data-unit=hq]').click();await expect(fallback.locator('#floor-panel')).toBeVisible();
  result.webglFallback='passed';
  const source=await readFile('index.html','utf8');assert.ok(source.includes('/src/main.tsx'));
  result.drivingEntryPreserved='passed';
  console.log(JSON.stringify(result,null,2));
} finally {await browser.close();}
